import 'dart:convert';
import 'dart:io';

import 'package:monstrous_core/monstrous_core.dart';
import 'package:monstrous_sim/monstrous_sim.dart';

/// Separate output is mandatory: never overwrites the retained October audit.
/// dart run bin/navigation_audit.dart OUTPUT_DIRECTORY [SEEDS_PER_CELL] [initial-income]
void main(List<String> args) {
  if (args.isEmpty) throw ArgumentError('Supply a new output directory.');
  final output = Directory(args.first);
  output.createSync(recursive: true);
  if (File('${output.path}/runs.json').existsSync() ||
      File('${output.path}/runs.json.gz').existsSync())
    throw StateError('Audit receipt already exists; choose a new directory.');
  final count = args.length > 1 ? int.parse(args[1]) : 200;
  if (count <= 0) throw ArgumentError('Seeds per cell must be positive.');
  if (args.length > 2 && args[2] != 'initial-income')
    throw ArgumentError('Unknown income bundle.');
  final initialIncome = args.length > 2;
  final runs = <Map<String, dynamic>>[];
  for (final mode in AuditMode.values) {
    for (final build in AuditBuild.values) {
      for (final policy in VoyagePolicy.values) {
        for (var i = 0; i < count; i++) {
          runs.add(
            const VoyageAuditRunner().run(
              seed: 20261105 + 31 * i,
              policy: policy,
              build: build,
              mode: mode,
              tuning: initialIncome
                  ? NavigationTuning(
                      huntWeight: build == AuditBuild.noCove ? 71 : 68,
                      coveWeight: build == AuditBuild.noCove ? 0 : 3,
                      economy: const VoyageEconomyTuning(
                        driftGoldMin: 70,
                        driftGoldMax: 90,
                        reachGoldMin: 100,
                        reachGoldMax: 130,
                      ),
                    )
                  : null,
            ),
          );
        }
        stdout.writeln(
          '${mode.name}/${build.name}/${policy.name}: $count runs',
        );
      }
    }
  }
  File('${output.path}/runs.json.gz')
      .writeAsBytesSync(gzip.encode(utf8.encode(jsonEncode(runs))));
  final totalsKeys =
      runs
          .expand((r) => (r['totals'] as Map<String, int>).keys)
          .toSet()
          .toList()
        ..sort();
  final csv = StringBuffer(
    'mode,build,policy,seed,terminalPhase,complete,krakenCrossed,died,stepLimited,error,region,leg,gold,hp,maxHp,firstMaxRegion,firstMaxLeg,${totalsKeys.join(',')}\n',
  );
  String escaped(Object? value) =>
      '"${(value ?? '').toString().replaceAll('"', '""')}"';
  for (final run in runs) {
    final end = run['final'] as Map;
    final max = run['firstMax'] as Map?;
    csv.writeln(
      [
        run['mode'],
        run['build'],
        run['policy'],
        run['seed'],
        run['terminalPhase'],
        run['complete'],
        run['krakenCrossed'],
        run['died'],
        run['stepLimited'],
        run['error'],
        end['region'],
        end['leg'],
        end['gold'],
        end['hp'],
        end['maxHp'],
        max?['region'],
        max?['leg'],
        for (final key in totalsKeys) (run['totals'] as Map)[key] ?? 0,
      ].map(escaped).join(','),
    );
  }
  File('${output.path}/runs.csv').writeAsStringSync(csv.toString());
  final report = StringBuffer(
    '# Navigation economy: seeded full-campaign observations\n\nGenerated by `packages/monstrous_sim/bin/navigation_audit.dart`. $count matched seeds per cell, base 20261105, stride 31. Fresh Standard and modestly progressed Standard (Tier II ancestral signature, carried 6 glass/4 bone/2 iron/1 barnacle); separate Carpenter, Exacting, combined and zero-cove scenarios. No production storage, inherited gold, trophy grants or legacy first-boss win flag. LIVE runs preserve real combat/death. Attrition/harsh REPLAYS force battle settlement with 15/22/30 or 30/40/50 ordinary hull loss and 35/50/70 Titan loss; clamp at 1 HP and count fatal shortfalls. Replay completion is assumed access, never survival evidence. Policies share combat tactics but differ in route/risk preference. All purchases and recoveries use core commands. Values remain provisional.\n\n',
  );
  report.writeln(
    '| Mode | Build | Policy | N | Kraken crossed | Full completion | Death | Error / limit | Maxed (R1/R2/R3) | Mean net gold | Mean earned / spent | Paid HP | Kits acquired / used | Glass / iron bought | Shrine opportunities / dedications |',
  );
  report.writeln(
    '| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | --- | ---: | --- | ---: | --- | --- | --- |',
  );
  for (final mode in AuditMode.values) {
    for (final build in AuditBuild.values) {
      for (final policy in VoyagePolicy.values) {
        final group = runs
            .where(
              (r) =>
                  r['mode'] == mode.name &&
                  r['build'] == build.name &&
                  r['policy'] == policy.name,
            )
            .toList();
        double mean(String key) =>
            group.fold<num>(
              0,
              (v, r) => v + ((r['totals'] as Map)[key] as num? ?? 0),
            ) /
            group.length;
        int n(bool Function(Map<String, dynamic>) test) =>
            group.where(test).length;
        final net =
            group.fold<num>(0, (v, r) => v + (r['final'] as Map)['gold']) /
            group.length;
        report.writeln(
          '| ${mode.name} | ${build.name} | ${policy.name} | ${group.length} | ${n((r) => r['krakenCrossed'] == true)} | ${n((r) => r['complete'] == true)} | ${n((r) => r['died'] == true)} | ${n((r) => r['error'] != null || r['stepLimited'] == true)} | ${[1, 2, 3].map((region) => n((r) => (r['firstMax'] as Map?)?['region'] == region)).join('/')} | ${net.toStringAsFixed(1)} | ${mean('goldEarned').toStringAsFixed(1)} / ${mean('goldSpent').toStringAsFixed(1)} | ${mean('paidRepairHp').toStringAsFixed(1)} | ${mean('kitsAcquired').toStringAsFixed(1)} / ${mean('kitsUsed').toStringAsFixed(1)} | ${mean('glassBought').toStringAsFixed(1)} / ${mean('ironBought').toStringAsFixed(1)} | ${mean('shrineOpportunities').toStringAsFixed(1)} / ${mean('dedications').toStringAsFixed(1)} |',
        );
      }
    }
  }
  report.writeln(
    '\nThese include early deaths; completion-conditioned milestones must be inspected separately. `runs.json.gz` retains per-voyage service/Titan snapshots, complete combat and cargo receipts, gold sources/spending, normal repair work, fixed refit HP, duties, kits/overflow, acquired materials and individual blueprint affordability. Individual affordability does not imply enough resources to buy every blueprint together. Zero-cove is a stress scenario, not the production offer distribution. Poor-kit observations are selected from natural acquisition, not fabricated stock. Simulator tactics do not estimate human win rates; player replay remains necessary.',
  );
  File('${output.path}/report.md').writeAsStringSync(report.toString());
}
